/**
 * Built-in offline "demo analyst" provider.
 *
 * Speaks the exact same JSON contract as the real providers, so the whole
 * pipeline (validation, ops application, versioning) is identical with or
 * without an API key. Useful for trying the product, for demos, and for
 * deterministic tests.
 */
import { sampleOrderFulfilmentMap } from '@eatransform/shared';

const IDS = { n: 0 };
const nid = (p = 'n') => `${p}_mock${++IDS.n}`;

function buildMap({ name, purpose, objective, owner, lanes, steps, kpis, risks }) {
  // steps: [laneIdx, type, label, extra]
  const laneObjs = lanes.map((l, i) => ({ id: nid('lane'), name: l[0], kind: l[1] || 'department', order: i }));
  const nodes = steps.map(([laneIdx, type, label, extra]) => ({
    id: nid(),
    type,
    label,
    laneId: laneObjs[laneIdx].id,
    ...(extra || {}),
  }));
  const edges = [];
  for (let i = 0; i < nodes.length - 1; i++) {
    edges.push({ id: nid('e'), source: nodes[i].id, target: nodes[i + 1].id });
  }
  return {
    name,
    type: 'swimlane',
    purpose,
    objective,
    owner,
    level: 1,
    departments: laneObjs.filter((l) => l.kind === 'department').map((l) => l.name),
    stakeholders: laneObjs.map((l) => l.name),
    lanes: laneObjs,
    nodes,
    edges,
    kpis,
    risks,
    metadata: { generatedBy: 'mock-analyst', notes: 'Generated by the offline demo analyst.' },
  };
}

